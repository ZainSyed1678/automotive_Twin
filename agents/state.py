"""
Graph state and report schemas for the LangGraph Diagnostic Agent.
"""

from typing import Any, Dict, List, Optional, TypedDict
from pydantic import BaseModel, Field


class DiagnosticReport(BaseModel):
    """
    Comprehensive, evidence-backed diagnostic report generated by the agent.
    Every claim is traceable to retrieved documents, similar cases, or simulation results.
    """
    case_id: Optional[str] = None
    top_fault_id: Optional[str] = None
    top_fault_name: Optional[str] = None
    component_id: Optional[str] = None
    confidence_score: float = Field(0.0, description="Posterior probability of top hypothesis")
    confidence_gap: float = Field(0.0, description="Probability margin over runner-up candidate")
    is_ambiguous: bool = False
    insufficient_evidence: bool = False
    ranked_hypotheses: List[Dict[str, Any]] = Field(default_factory=list)
    supporting_evidence: List[str] = Field(default_factory=list)
    contradictory_evidence: List[str] = Field(default_factory=list)
    recommended_tests: List[str] = Field(default_factory=list)
    citations: List[str] = Field(default_factory=list)
    executive_summary: str = ""


class DiagnosticState(TypedDict, total=False):
    """
    Typed state dictionary passed through LangGraph workflow nodes.
    """
    case_id: Optional[str]
    raw_input: Optional[str]
    observations: Dict[str, Any]
    retrieved_docs: List[Dict[str, Any]]
    similar_cases: List[Dict[str, Any]]
    candidate_hypotheses: List[str]
    simulation_results: Dict[str, Dict[str, Any]]
    diagnostic_result: Optional[Dict[str, Any]]
    citations: List[str]
    final_report: Optional[Dict[str, Any]]
